-- Food tax rates for the whole of Colorado, and who collects each tax.
--
-- Until now food_tax_rates held six Denver-area counties and 26 cities, so
-- checkout found no rate for most of the state. This adds:
--
--   * a collected_by column: 'state' when the Colorado Department of Revenue
--     collects the tax, 'self' when the city (or Denver and Broomfield, each a
--     city and county in one) collects its own, NULL for a place with no
--     sales tax at all. Checkout doesn't read it; it tells Jesse where to
--     file. Every existing row gets a value below.
--   * the other 58 counties. A county with no sales tax gets a 0% row, so
--     checkout knows it was checked rather than missing. Delta and Montrose
--     each have a public safety (PSI) tax that covers the whole county and
--     taxes food, so it is added to the county rate.
--   * every state-collected city in DR 1002 ("Colorado Sales/Use Tax Rates",
--     July 2026) that wasn't already here: 164 of its 170 rows. A city exempts
--     food when DR 1002 lists exemption code A.
--   * Bow Mar, which has no town sales tax, and 18 large home-rule cities
--     that collect their own tax. DR 1002 doesn't give their food rule, so
--     each one comes from the city's own website or code (checked
--     2026-10-21). Loveland and Grand Junction stay unconfirmed: we couldn't
--     read a city source that settles the food rule. Their notes say why.
--
-- Rows are confirmed, so checkout charges them, except Loveland, Grand
-- Junction and Basalt. An address with an unconfirmed row, or no row, gets
-- no local tax (his decision, 2026-10-21). The admin order page shows
-- "No local rate on file" on those orders.
-- Basalt stays unconfirmed because the Pitkin County rate is lower inside
-- Basalt than this table can show (see its note).
--
-- Superior and Louisville tax at 3.775%. food_rate_bps holds whole
-- hundredths of a percent, so those rows hold 378 (3.78%), as the state's
-- rate sheet shows for Superior. Each note says so.
--
-- Sources: DR 1002, July 2026 (https://tax.colorado.gov/DR1002) and the
-- state's rate sheet (Colorado_Jurisdiction_Codes_Rates_July-Dec2026.xlsx on
-- tax.colorado.gov). Each Census code was checked against the Census
-- Bureau's 2020 Colorado place and county code lists.
--
-- Safe to run twice: the column is added only if missing, the backfill only
-- fills empty values, and ON CONFLICT DO NOTHING skips any place already in
-- the table (by name or Census code). No existing rate changes.

ALTER TABLE public.food_tax_rates
  ADD COLUMN IF NOT EXISTS collected_by TEXT
  CONSTRAINT food_tax_rates_collected_by_check
  CHECK (collected_by IN ('state', 'self'));

-- Self-collected: Denver and Broomfield (city and county) and the home-rule
-- cities already in the table. DR 1002 lists each of these cities among the
-- "home rule cities for which the state does not collect local sales tax".
UPDATE public.food_tax_rates
SET collected_by = 'self'
WHERE collected_by IS NULL
  AND (
    (kind = 'county' AND name IN ('Denver County', 'Broomfield County'))
    OR (kind = 'city' AND name IN (
      'Denver', 'Broomfield', 'Arvada', 'Aurora', 'Centennial',
      'Cherry Hills Village', 'Commerce City', 'Englewood', 'Federal Heights',
      'Glendale', 'Golden', 'Greenwood Village', 'Lakewood', 'Littleton',
      'Lone Tree', 'Northglenn', 'Sheridan', 'Thornton', 'Westminster',
      'Wheat Ridge'))
  );

-- State-collected: the other counties, the towns DR 1002 lists and the two
-- districts.
UPDATE public.food_tax_rates
SET collected_by = 'state'
WHERE collected_by IS NULL
  AND (
    (kind = 'county' AND name IN (
      'Adams County', 'Arapahoe County', 'Douglas County', 'Jefferson County'))
    OR (kind = 'city' AND name IN (
      'Columbine Valley', 'Edgewater', 'Foxfield', 'Lakeside', 'Morrison',
      'Mountain View'))
    OR (kind = 'district' AND name IN (
      'Southeast Jefferson County LID', 'Lincoln Station LID'))
  );

-- Weld County now has a row, so these notes no longer hold.
UPDATE public.food_tax_rates
SET notes = replace(notes,
  'Weld County, which is not in this table, so those addresses go to review.',
  'Weld County, which has no county sales tax.')
WHERE kind = 'city'
  AND name IN ('Thornton', 'Northglenn')
  AND notes LIKE '%Weld County, which is not in this table, so those addresses go to review.%';

